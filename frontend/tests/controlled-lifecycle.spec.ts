import { expect, test } from "@playwright/test";

test("controlled external responses: browser → four agents → webhook → audited dashboard", async ({ page, request }) => {
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto("/");
  await expect(page.getByText("API conectada", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Nova solicitação", exact: true }).click();
  const form = page.getByRole("dialog", { name: "Nova solicitação" });
  await form.getByLabel("Nome do item").fill("Capacete industrial certificado");
  await form.getByLabel("Quantidade", { exact: true }).fill("100");
  await form.getByLabel("Local de entrega / CEP").fill("CEP inválido");
  await form.getByRole("button", { name: "Pesquisar fornecedores reais" }).click();
  await expect(form.getByRole("alert")).toContainText("CEP com oito dígitos");
  expect((await (await request.get("/api/godmode/dashboard")).json()).total_runs).toBe(0);
  await form.getByLabel("Local de entrega / CEP").fill("CEP 01001-000, SP");
  await form.getByRole("button", { name: "Pesquisar fornecedores reais" }).click();
  await expect(form).not.toBeVisible();
  const dashboard = async () => (await (await request.get("/api/godmode/dashboard")).json());
  await expect.poll(async () => (await dashboard()).runs[0].status).toBe("NEGOTIATING");
  const row = (await dashboard()).runs[0];
  expect(row.qty).toBe(100);
  expect(row.target_price).toBe("8500.00");
  await page.locator("#kanban").getByRole("button", { name: /Capacete industrial certificado/ }).click();
  const drawer = page.getByRole("dialog", { name: "Capacete industrial certificado" });
  await expect(drawer.getByRole("region", { name: "Composição do TCO" })).toContainText("Não confirmadas");
  await drawer.getByRole("button", { name: "Acompanhar conversa ao vivo" }).click();
  const chat = page.getByRole("dialog", { name: /Negociação/ });
  await expect(chat.getByRole("log")).toContainText("Confirma preço unitário");
  const post = (update: number, message: number, text: string) => request.post("http://127.0.0.1:8001/webhook/telegram", { headers: { "X-Telegram-Bot-Api-Secret-Token": "controlled-webhook-secret" }, data: { update_id: update, message: { message_id: update + 1000, chat: { id: 555123, type: "private" }, reply_to_message: { message_id: message }, text } } });
  const initial = "R$ 110 cada, 100 unidades, frete R$ 200, Seguro R$ 20, 5 dias úteis, Pix, CEP 01001-000";
  expect((await post(701, 101, initial)).ok()).toBe(true);
  await expect(chat.getByRole("log")).toContainText("Consegue R$ 8500.00 no total");
  expect((await (await post(701, 101, initial)).json()).duplicate).toBe(true);
  const final = "Confirmo R$ 80 cada, 100 unidades, frete R$ 40, Seguro R$ 10, 5 dias úteis, Pix, CEP 01001-000";
  expect((await post(702, 104, final)).ok()).toBe(true);
  await expect.poll(async () => (await dashboard()).runs[0].status).toBe("DONE");
  await expect(chat.getByRole("log")).toContainText(final);
  await expect(chat.locator("article.bg-slate-200")).toHaveCount(2);
  await expect(chat.locator("article.bg-blue-600").first()).toBeVisible();
  await chat.getByRole("button", { name: "Fechar conversa" }).click();
  await expect(drawer.getByRole("region", { name: "Composição do TCO" })).toContainText("R$ 8.050,00");
  await expect(drawer.getByRole("region", { name: "Composição do TCO" })).toContainText("Seguro");
  await expect(drawer.getByRole("region", { name: "Parecer do auditor" })).toContainText("Evidências:");
  await drawer.getByRole("button", { name: "Fechar detalhes" }).click();
  const metrics = page.getByRole("region", { name: "Indicadores de economia" });
  for (const text of ["R$ 3.000,00", "R$ 2.500,00", "R$ 8.050,00"]) await expect(metrics.getByText(text, { exact: true })).toBeVisible();
  await page.reload();
  await expect(metrics.getByText("R$ 8.050,00", { exact: true })).toBeVisible();
  const state = await dashboard();
  expect(state.runs[0].quote.initial_price).toBe("110");
  expect(state.runs[0].audit.savings_status).toBe("negotiated");
  const traces = await (await request.get(`/api/request/${row.id}/trace`)).json();
  expect(new Set(traces.map((trace: { node: string }) => trace.node)).size).toBe(4);
  await page.screenshot({ path: "../artifacts/final/controlled-lifecycle.png", fullPage: true });
  expect(errors).toEqual([]);
});

test("observer rejects a different request, retains messages on errors, deduplicates and cleans up polling", async ({ page }) => {
  await page.goto("/");
  await page.locator("#kanban").getByRole("button", { name: /Capacete industrial certificado/ }).click();
  let mode = "valid"; let polls = 0;
  const message = { id: 42, request_id: 1, supplier_domain: "example.com", sender_type: "AI", text: "Mensagem controlada", timestamp: new Date().toISOString(), delivery_status: "sent" };
  await page.route("**/api/chat/1", async route => {
    polls++;
    if (mode === "error") return route.fulfill({ status: 503, json: { detail: "Falha de teste" } });
    return route.fulfill({ json: mode === "wrong" ? [{ ...message, request_id: 999, text: "Conversa alheia" }] : [message, message] });
  });
  await page.getByRole("button", { name: "Acompanhar conversa ao vivo" }).click();
  const chat = page.getByRole("dialog", { name: /Negociação/ });
  await expect(chat.getByText("Mensagem controlada", { exact: true })).toHaveCount(1);
  mode = "wrong";
  await expect(chat.getByRole("alert")).toContainText("Histórico incompatível");
  await expect(chat.getByText("Conversa alheia")).toHaveCount(0);
  mode = "error";
  await expect(chat.getByRole("alert")).toContainText("Falha de teste");
  await expect(chat.getByText("Mensagem controlada", { exact: true })).toBeVisible();
  await chat.getByRole("button", { name: "Fechar conversa" }).click();
  const stopped = polls;
  await page.waitForTimeout(3300);
  expect(polls).toBe(stopped);
});
