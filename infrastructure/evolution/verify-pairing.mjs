import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { handleCompanionRegRefresh, makePairingQRRenderer } from './node_modules/baileys/lib/Utils/companion-reg-client-utils.js';
import * as baileys from 'baileys';

assert.equal(typeof baileys.default, 'function', 'Evolution must be able to load the socket factory');
const logger = { info() {}, debug() {}, warn() {} };
const creds = { advSecretKey: 'old-secret' };
const emitted = [], rendered = [];
const renderer = makePairingQRRenderer(['ref-1','ref-2'], ref => rendered.push([ref,creds.advSecretKey]));
assert.equal(renderer.refresh(), false);
assert.equal(renderer.next(), true);
const context = { creds, logger, emitCredsUpdate: c => emitted.push(c), refreshQR: () => renderer.refresh() };
const notification = tag => ({ tag:'notification', attrs:{type:'companion_reg_refresh',id:'test'}, content:[{tag,attrs:{}}] });
assert.equal(handleCompanionRegRefresh(notification('companion_reg_refresh'), context),'rotated');
assert.notEqual(creds.advSecretKey,'old-secret');
assert.equal(Buffer.from(creds.advSecretKey,'base64').length,32);
assert.deepEqual(rendered.map(r=>r[0]),['ref-1','ref-1']);
assert.equal(emitted.length,1);
assert.equal(renderer.next(),true);
assert.equal(rendered.at(-1)[0],'ref-2');
assert.equal(handleCompanionRegRefresh(notification('pair-device-rotate-qr'),context),'rotated');
assert.equal(renderer.next(),false);
const before=creds.advSecretKey;
creds.me={id:'already-paired'};
assert.equal(handleCompanionRegRefresh(notification('companion_reg_refresh'),context),'ignored_registered');
assert.equal(creds.advSecretKey,before);
assert.equal(handleCompanionRegRefresh(notification('unexpected'),context),'ignored_malformed');
const recv=readFileSync('./node_modules/baileys/lib/Socket/messages-recv.js','utf8');
assert.ok(recv.includes('buildAckStanza(node, errorCode, authState.creds.me?.id)'));
console.log('PASS pairing compatibility: imports, secret refresh, same QR reference, alternate notification, registered-session guard and pre-login ACK guard');
